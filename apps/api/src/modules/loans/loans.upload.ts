import { mkdirSync } from 'node:fs';
import path from 'node:path';
import multer from 'multer';
import type { Request } from 'express';
import { getEnv } from '../../config/env.js';
import { badRequest } from '../../errors/AppError.js';
import { logger } from '../../utils/logger.js';

const env = getEnv();

const RECEIPTS_DIR = path.join('receipts');
const UPLOAD_ROOT = path.join(env.uploadDir, RECEIPTS_DIR);

mkdirSync(UPLOAD_ROOT, { recursive: true });

const ALLOWED_MIME_TYPES = new Set(['image/jpeg', 'image/png', 'image/webp', 'image/heic']);
const EXTENSION_BY_MIME: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/heic': '.heic',
};

const storage = multer.diskStorage({
  destination: (_req, _file, cb) => {
    cb(null, UPLOAD_ROOT);
  },
  filename: (req: Request, file, cb) => {
    // The filename is generated by the server - the client never influences it.
    const loanId = String(req.params.id ?? 'loan').replace(/[^a-zA-Z0-9-]/g, '');
    const extension = EXTENSION_BY_MIME[file.mimetype] ?? '.bin';
    const unique = `${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
    cb(null, `${loanId}-${unique}${extension}`);
  },
});

/**
 * Multer middleware for the receipt upload.
 * Only small image files are accepted; anything else is rejected with a
 * user friendly error.
 */
export const uploadReceipt = multer({
  storage,
  limits: {
    fileSize: env.maxUploadBytes,
    files: 1,
    fields: 4,
  },
  fileFilter: (_req, file, cb) => {
    if (!ALLOWED_MIME_TYPES.has(file.mimetype)) {
      cb(
        badRequest(
          'Only JPEG, PNG, WEBP or HEIC images can be attached as a receipt.',
          'UNSUPPORTED_FILE_TYPE',
        ),
      );
      return;
    }
    cb(null, true);
  },
}).single('receipt');

/**
 * Middleware that runs after the upload and exposes the stored relative path
 * on `req.body.receiptPath`.
 */
export function attachReceiptPath(req: Request, _res: unknown, next: () => void): void {
  const file = req.file;
  if (!file) {
    next();
    return;
  }
  const relativePath = path.posix.join(RECEIPTS_DIR, path.basename(file.filename));
  req.body = { ...(req.body ?? {}), receiptPath: relativePath };
  logger.info(`Stored receipt ${relativePath} (${file.size} bytes)`);
  next();
}

/** Resolves a stored relative receipt path to an absolute path on disk. */
export function resolveReceiptPath(relativePath: string): string {
  const resolved = path.resolve(env.uploadDir, relativePath);
  // Prevent path traversal outside of the upload directory.
  if (!resolved.startsWith(path.resolve(env.uploadDir))) {
    throw badRequest('Invalid receipt path.', 'INVALID_RECEIPT_PATH');
  }
  return resolved;
}
